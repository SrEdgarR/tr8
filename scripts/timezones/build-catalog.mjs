import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

// Offline, deterministic generation from the attributed source extracts documented
// in docs/time-zones.md. Source files and ZIP archives are deliberately not shipped.
const sourceIndex = process.argv.indexOf('--source-dir');
if (sourceIndex < 0 || !process.argv[sourceIndex + 1]) throw new Error('Usage: node scripts/timezones/build-catalog.mjs --source-dir <directory>');
const sourceDirectory = resolve(process.argv[sourceIndex + 1]);
const projectDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourceFiles = ['cities15000.txt', 'zone.tab', 'iso3166.tab', 'admin1CodesASCII.txt', 'timeZoneNames-es.json'];
const sources = Object.fromEntries(await Promise.all(sourceFiles.map(async name => [name, await readFile(resolve(sourceDirectory, name), 'utf8')])));
const hashes = Object.fromEntries(sourceFiles.map(name => [name, createHash('sha256').update(sources[name]).digest('hex')]));
const normalize = value =>
  value
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
const clean = value => value.replace(/[\t\n\r|]/g, ' ').trim();
const sourceRows = sources['cities15000.txt']
  .trim()
  .split(/\r?\n/)
  .map(row => row.split('\t'))
  .sort((a, b) => Number(b[14]) - Number(a[14]) || Number(a[0]) - Number(b[0]));
const countries = sources['iso3166.tab']
  .split(/\r?\n/)
  .filter(row => row && !row.startsWith('#'))
  .map(row => row.split('\t').slice(0, 2));
// GeoNames uses XK for Kosovo; IANA's ISO country table does not include that
// user-assigned code. Keep its cities with their GeoNames zone assignment.
countries.push(['XK', 'Kosovo']);
const countryNames = new Map(countries);
const spanishCities = new Map();
function visitZoneTree(tree, prefix = '') {
  for (const [key, value] of Object.entries(tree)) {
    if (!value || typeof value !== 'object') continue;
    const zone = prefix ? `${prefix}/${key}` : key;
    if (value.exemplarCity) spanishCities.set(zone, value.exemplarCity);
    visitZoneTree(value, zone);
  }
}
visitZoneTree(JSON.parse(sources['timeZoneNames-es.json']).main.es.dates.timeZoneNames.zone);
const zones = [];
const zoneIndices = new Map();
function zoneIndex(country, zone) {
  const key = `${country}|${zone}`;
  if (!zoneIndices.has(key)) {
    zoneIndices.set(key, zones.length);
    const fallbackCity = zone.split('/').at(-1).replaceAll('_', ' ');
    zones.push([country, zone, spanishCities.get(zone) || fallbackCity]);
  }
  return zoneIndices.get(key);
}
for (const row of sources['zone.tab'].split(/\r?\n/).filter(row => row && !row.startsWith('#'))) {
  const [country, , zone] = row.split('\t');
  zoneIndex(country, zone);
}
const adminSource = new Map(
  sources['admin1CodesASCII.txt']
    .trim()
    .split(/\r?\n/)
    .map(row => {
      const [code, name] = row.split('\t');
      return [code, name];
    }),
);
const regions = [];
const regionIndices = new Map();
function regionIndex(country, code) {
  const name = adminSource.get(`${country}.${code}`);
  if (!name) return '';
  if (!regionIndices.has(name)) {
    regionIndices.set(name, regions.length);
    regions.push(name);
  }
  return regionIndices.get(name);
}
const cities = [];
for (const row of sourceRows) {
  const country = row[8];
  const zone = row[17];
  if (!countryNames.has(country) || !zone?.includes('/')) continue;
  // All principal/ascii city names are searchable. Latin alternate names for large
  // cities add a bounded set of alternatives without shipping the full multilingual
  // gazetteer. CLDR's Spanish IANA exemplar names are always included separately.
  const aliases = [
    row[2],
    ...(Number(row[14]) >= 100_000
      ? row[3].split(',').filter(value => /^[\p{Script=Latin}\p{Number}\p{Punctuation}\p{Separator}]+$/u.test(value) && value.length <= 64)
      : []),
  ];
  const normalizedName = normalize(row[1]);
  const deduplicatedAliases = [...new Set(aliases.map(normalize).filter(value => value && value !== normalizedName))].slice(0, 2);
  cities.push([clean(row[1]), country, zoneIndex(country, zone), regionIndex(country, row[10]), deduplicatedAliases.map(clean).join('|')]);
}
// Grouping improves static compression. Within each zone the original population
// order is retained, so larger homonymous places appear before smaller ones.
cities.sort((a, b) => a[1].localeCompare(b[1], 'en') || a[2] - b[2]);
const data = { countries, zones, regions, cities: cities.map(row => row.join('\t')).join('\n'), sourceHashes: hashes };
const output = `// Generated by scripts/timezones/build-catalog.mjs. Do not edit manually.\n// GeoNames CC BY 4.0; IANA public domain; Unicode CLDR Unicode-3.0.\n// Sources, scope, attribution and regeneration: docs/time-zones.md.\n// prettier-ignore\nexport default ${JSON.stringify(data)};\n`;
await writeFile(resolve(projectDirectory, 'src/app/workspace/timeZonesCatalog.ts'), output, 'utf8');
console.log(
  JSON.stringify(
    { cities: cities.length, zones: zones.length, sourceBytes: Buffer.byteLength(output), gzipBytes: gzipSync(output).length, sourceHashes: hashes },
    null,
    2,
  ),
);
